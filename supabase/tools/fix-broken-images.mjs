// Finds catalog images (auras + achievements) whose wiki file no longer
// exists, looks up each one's current image on the Sol's RNG wiki, and prints
// SQL to fix them. Review the output, then paste it into the Supabase SQL
// editor.
//
// Run from the repo root (reads the Supabase URL + key from .env.local):
//   node --env-file=.env.local supabase/tools/fix-broken-images.mjs > fix-images.sql
//
// Only reads data — it never writes to the database itself.

const SUPABASE_URL = process.env.NEXT_PUBLIC_SUPABASE_URL;
const SUPABASE_KEY = process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY;
const WIKI_API = process.env.WIKI_API ?? "https://sol-rng.fandom.com/api.php";
const TABLES = ["auras", "achievements"];

if (!SUPABASE_URL || !SUPABASE_KEY) {
  console.error("Missing NEXT_PUBLIC_SUPABASE_URL / NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY.");
  console.error("Run with: node --env-file=.env.local supabase/tools/fix-broken-images.mjs");
  process.exit(1);
}

const log = (...a) => console.error(...a); // progress → stderr, SQL → stdout
const sqlString = (s) => `'${s.replace(/'/g, "''")}'`;

async function loadRows(table) {
  const res = await fetch(`${SUPABASE_URL}/rest/v1/${table}?select=id,name,image_url&order=id`, {
    headers: { apikey: SUPABASE_KEY, Authorization: `Bearer ${SUPABASE_KEY}` },
  });
  if (!res.ok) throw new Error(`Loading ${table} failed: ${res.status} ${await res.text()}`);
  return res.json();
}

// true = image exists, false = gone (404/410), null = couldn't tell.
async function imageExists(url) {
  try {
    let res = await fetch(url, { method: "HEAD", redirect: "follow" });
    if (res.status === 405) res = await fetch(url, { redirect: "follow" });
    if (res.status === 404 || res.status === 410) return false;
    return res.ok ? true : null;
  } catch {
    return null;
  }
}

// The lead image of the wiki page named after the aura / achievement.
async function wikiImageFor(name) {
  const params = new URLSearchParams({
    action: "query",
    prop: "pageimages",
    piprop: "original",
    redirects: "1",
    format: "json",
    titles: [name, `${name} (Aura)`].join("|"),
  });
  const res = await fetch(`${WIKI_API}?${params}`, {
    headers: { "User-Agent": "SolsChecklist image fixer" },
  });
  if (!res.ok) return null;
  const data = await res.json();
  for (const page of Object.values(data?.query?.pages ?? {})) {
    if (page.original?.source) return { url: page.original.source, page: page.title };
  }
  return null;
}

// Run `fn` over `items` with a few requests in flight at a time.
async function mapLimit(items, limit, fn) {
  const out = new Array(items.length);
  let i = 0;
  await Promise.all(
    Array.from({ length: limit }, async () => {
      while (i < items.length) {
        const idx = i++;
        out[idx] = await fn(items[idx]);
      }
    }),
  );
  return out;
}

const fixes = [];
const notFound = [];
const unsure = [];

for (const table of TABLES) {
  const rows = (await loadRows(table)).filter((r) => r.image_url);
  log(`Checking ${rows.length} ${table} images…`);
  const status = await mapLimit(rows, 6, (r) => imageExists(r.image_url));

  for (const [idx, row] of rows.entries()) {
    if (status[idx] === null) unsure.push(`${table}: ${row.name} (${row.image_url})`);
    if (status[idx] !== false) continue;
    const found = await wikiImageFor(row.name);
    if (found && found.url !== row.image_url && (await imageExists(found.url)) !== false) {
      fixes.push({ table, row, found });
      log(`  fixed   ${table}: ${row.name} → ${found.url}`);
    } else {
      notFound.push(`${table}: ${row.name} (${row.image_url})`);
      log(`  no match ${table}: ${row.name}`);
    }
  }
}

console.log("-- Generated by supabase/tools/fix-broken-images.mjs");
console.log("-- Review before running in the Supabase SQL editor.\n");
for (const { table, row, found } of fixes) {
  console.log(`-- ${row.name}: was ${row.image_url} (wiki page: ${found.page})`);
  console.log(`update public.${table} set image_url = ${sqlString(found.url)} where id = ${row.id};`);
}
if (notFound.length) {
  console.log("\n-- Broken, but no replacement found on the wiki — fix these by hand:");
  for (const line of notFound) console.log(`--   ${line}`);
}
if (unsure.length) {
  console.log("\n-- Couldn't check (network error or unexpected status):");
  for (const line of unsure) console.log(`--   ${line}`);
}
log(`\nDone: ${fixes.length} fixable, ${notFound.length} need a manual fix, ${unsure.length} unchecked.`);
